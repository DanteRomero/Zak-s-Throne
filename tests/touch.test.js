/* Controles táctiles: ejecutar con browser_check.py index.html --touch --width 844 --height 390 --script tests/touch.test.js */
(async () => {
  'use strict';
  window.ZAK_CONFIG = {supabaseUrl: '', supabaseKey: ''}; // Las pruebas nunca publican en el ranking real.
  const g = window.zakGame, results = [];
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const assert = (name, condition) => results.push({name, pass: !!condition});
  const pointer = (node, type, x, y, id = 7) => node.dispatchEvent(new PointerEvent(type, {bubbles: true, cancelable: true, pointerId: id, pointerType: 'touch', clientX: x, clientY: y, isPrimary: true}));
  g.settings.tutorial = false;
  document.getElementById('new-game').click();
  document.getElementById('player-name').value = 'Pulgar';
  document.getElementById('begin-adventure').click();
  const zone = document.getElementById('joystick-zone'), box = zone.getBoundingClientRect();
  assert('Joystick visible en pantalla táctil', box.width > 100 && getComputedStyle(document.getElementById('touch-controls')).display !== 'none');
  const startX = g.player.x, cx = box.left + 90, cy = box.bottom - 90;
  pointer(zone, 'pointerdown', cx, cy); pointer(zone, 'pointermove', cx + 60, cy);
  assert('Arrastrar el joystick produce dirección analógica', g.stick.x > .9 && Math.abs(g.stick.y) < .05);
  await wait(500);
  assert('El personaje camina con el joystick', g.player.x > startX + 20);
  pointer(zone, 'pointerup', cx + 60, cy);
  assert('Soltar el joystick frena', g.stick.x === 0 && g.stick.y === 0);
  const run = document.getElementById('touch-run'); pointer(run, 'pointerdown', 0, 0);
  assert('Correr se activa con un toque', g.runToggle === true);
  pointer(run, 'pointerdown', 0, 0); assert('Correr se desactiva con otro toque', g.runToggle === false);
  const thief = g.enemies.find(e => e.type === 'thief');
  Object.assign(g.player, {x: thief.x - 25, y: thief.y + 10, dir: 'down'}); g.biome = thief.biome; thief.stun = 50;
  const hp = thief.hp, attack = document.getElementById('touch-attack');
  pointer(attack, 'pointerdown', 0, 0, 9); pointer(attack, 'pointerup', 0, 0, 9);
  assert('El ataque táctil apunta solo al enemigo cercano', thief.hp < hp && g.player.dir === 'right');
  // Analógico de ataque: mantener apunta y muestra el indicador; soltar ataca.
  const knob = attack.querySelector('.aim-knob'), step = () => g.update(.016), ready = () => { g.player.attackCooldown = 0; g.player.attackAnim = 0; };
  thief.hp = thief.maxHp; ready(); Object.assign(g.player, {x: thief.x - 25, y: thief.y + 10});
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 700, 340, 9);
  assert('Inclinar el analógico fija la dirección y mueve la perilla', Math.abs(g.attackStick.x) < .01 && g.attackStick.y > .99 && knob.style.transform.includes('translate'));
  for (let k = 0; k < 40; k++) step();
  assert('Mantenerlo inclinado apunta pero no ataca', g.player.dir === 'down' && g.player.attackAnim === 0 && thief.hp === thief.maxHp);
  pointer(attack, 'pointerup', 700, 340, 9);
  assert('Soltarlo ataca hacia donde apuntaba, no al enemigo cercano', g.player.attackY > .99 && g.player.attackAnim > 0 && thief.hp === thief.maxHp);
  assert('Soltar limpia el analógico', g.attackStick === null && g.attackPreview === false && !attack.classList.contains('active') && knob.style.transform === '');
  ready(); pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 740, 300, 9); pointer(attack, 'pointerup', 740, 300, 9);
  assert('Soltarlo apuntando al enemigo le pega', g.player.dir === 'right' && g.player.attackX > .99 && thief.hp < thief.maxHp);
  ready(); const cancelled = thief.hp;
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 740, 300, 9); pointer(attack, 'pointermove', 700, 300, 9);
  assert('Volver al centro apaga el indicador', g.attackStick === null && g.attackPreview === false);
  pointer(attack, 'pointerup', 700, 300, 9);
  assert('Soltar en el centro después de apuntar cancela el golpe', thief.hp === cancelled && g.player.attackAnim === 0);
  ready(); const walkFrom = g.player.x;
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 660, 300, 9); g.stick = {x: 1, y: 0}; step();
  assert('Se puede caminar para un lado y apuntar para el otro', g.player.x > walkFrom && g.player.dir === 'left' && g.player.attackAnim === 0);
  g.stick = {x: 0, y: 0}; pointer(attack, 'pointerup', 660, 300, 9);
  assert('Y al soltar ataca para ese lado', g.player.attackX < -.99 && g.player.attackAnim > 0);
  Object.assign(g.player, {x: thief.x - 25, y: thief.y + 10}); ready(); const beforeHold = thief.hp;
  pointer(attack, 'pointerdown', 700, 300, 9);
  assert('Un toque corto todavía no muestra el indicador', g.attackPreview === false);
  await wait(220);
  assert('Mantenerlo sin mover muestra hacia el enemigo cercano y no ataca', g.attackPreview === true && g.attackVector()[0] > .5 && thief.hp === beforeHold);
  pointer(attack, 'pointerup', 700, 300, 9);
  assert('Al soltarlo ataca a ese enemigo', thief.hp < beforeHold && g.attackPreview === false);
  ready(); g.player.attackCooldown = .1;
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 660, 300, 9); pointer(attack, 'pointerup', 660, 300, 9);
  assert('Soltar justo antes de que esté listo no ataca todavía', g.player.attackAnim === 0 && !!g.attackQueue);
  for (let k = 0; k < 10; k++) step();
  assert('Pero el golpe no se pierde: sale apenas está listo', g.player.attackX < -.99 && g.player.attackAnim > 0 && !g.attackQueue);
  ready(); g.player.attackCooldown = 5;
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 660, 300, 9); pointer(attack, 'pointerup', 660, 300, 9);
  for (let k = 0; k < 30; k++) step();
  assert('Si falta mucho para estar listo, el golpe se descarta', !g.attackQueue && g.player.attackAnim === 0);
  // Línea de los tiros: termina donde pega de verdad.
  ready(); g.player.weapon = 'bow'; Object.assign(g.player, {x: thief.x - 45, y: thief.y + 1}); thief.hp = thief.maxHp;
  g.attackStick = {x: 1, y: 0}; const path = g.attackPath();
  assert('La línea del tiro termina en el primer enemigo', path.target === thief && path.x1 < thief.x);
  g.attack(); g.attackStick = null; for (let k = 0; k < 30; k++) step();
  assert('La flecha pega donde marcaba la línea', thief.hp < thief.maxHp);
  const everyone = g.enemies; g.enemies = [];
  g.attackStick = {x: 0, y: 1}; const free = g.attackPath(); g.attackStick = null; g.enemies = everyone;
  assert('Sin nada en el medio, la línea llega hasta el alcance del arma o el obstáculo', free.target === null && (free.blocked || Math.abs(Math.hypot(free.x1 - free.x0, free.y1 - free.y0) - Zak.WEAPON_TYPES.bow.range) < 1));
  const rock = g.world.objects.find(o => o.solid && o.w > 12 && o.h > 8); Object.assign(g.player, {x: rock.x - 60, y: rock.y + rock.h / 2 + 7});
  g.attackStick = {x: 1, y: 0}; const wall = g.attackPath(); g.attackStick = null;
  assert('Un obstáculo corta la línea', wall.blocked && wall.x1 <= rock.x + 3);
  g.player.weapon = 'fists'; Object.assign(g.player, {x: thief.x - 25, y: thief.y + 10}); ready();
  pointer(attack, 'pointerdown', 700, 300, 9); pointer(attack, 'pointermove', 740, 300, 9); g.pause();
  assert('Pausar suelta el analógico', g.attackStick === null && g.attackPreview === false);
  pointer(attack, 'pointermove', 700, 340, 9); assert('En pausa no apunta', g.attackStick === null);
  g.resume(); pointer(attack, 'pointerup', 700, 340, 9);
  g.player.weapons.push('bow'); g.player.weapon = 'fists'; pointer(document.getElementById('touch-weapon'), 'pointerdown', 0, 0);
  assert('El botón de arma rota entre las conseguidas', g.player.weapon === 'bow');
  g.player.rollCooldown = 0; pointer(document.getElementById('touch-roll'), 'pointerdown', 0, 0);
  assert('Rodar desde el botón', g.player.roll > 0);
  const actions = document.querySelector('.touch-actions'), small = actions.getBoundingClientRect().width;
  const css = name => getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  assert('Los controles arrancan en tamaño chico, con botones un poco más grandes que el joystick', css('--tc') === '0.7' && css('--tb') === '0.82' && small > 170 && small < 190);
  document.getElementById('pause-button').click();
  [...document.querySelectorAll('#modal-content button')].find(b => b.textContent === 'Opciones y controles').click();
  const size = document.querySelector('[aria-label="Tamaño de los controles táctiles"]'); size.click();
  assert('Opciones permite agrandar los controles', size.textContent === 'MEDIANOS' && actions.getBoundingClientRect().width > small && JSON.parse(localStorage.getItem('zak.throne.settings.v1')).controls === 'medium');
  size.click(); size.click();
  assert('El tamaño vuelve a chico al recorrer las opciones', size.textContent === 'CHICOS');
  document.getElementById('close-modal').click(); document.getElementById('close-modal').click();
  g.pause(); g.resume();
  return {passed: results.filter(r => r.pass).length, failed: results.filter(r => !r.pass).length, results};
})()
